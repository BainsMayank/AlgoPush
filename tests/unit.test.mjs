// Pure-logic tests for the streak engine, index restore and milestones.
// No browser, no network: `node tests/unit.test.mjs`.
import { computeRun, dayNumber, dayNumbers, dayString, weekStart, FREEZE_MAX } from '../shared/streak.js';
import { parseRootReadme, mergeIntoIndex, entryFromShared } from '../shared/index-restore.js';

const store = {};
globalThis.chrome = {
    storage: {
        local: {
            get: async (keys) => Object.fromEntries([].concat(keys).filter((k) => k in store).map((k) => [k, store[k]])),
            set: async (values) => { Object.assign(store, values); }
        }
    }
};
const { milestonesFor, takeNewMilestones } = await import('../shared/milestones.js');

let failures = 0;
function check(name, ok, detail = '') {
    console.log(`${ok ? 'PASS' : 'FAIL'}  ${name}${ok ? '' : `  ${detail}`}`);
    if (!ok) failures += 1;
}

/* ── streaks and freezes ───────────────────────────────────────────── */

const T = dayNumber('2026-10-01');
const set = (...offsets) => new Set(offsets.map((o) => T + o));

let r = computeRun(set(), T);
check('no solves, no run', r.run === 0 && r.freezes === 0 && r.longest === 0);

r = computeRun(set(-2, -1), T);
check('today unfinished does not break a run', r.run === 2 && !r.activeToday);

r = computeRun(set(-3, -2), T);
check('a missed day with no freeze breaks it', r.run === 0 && r.longest === 2, JSON.stringify(r));

r = computeRun(set(-6, -5, -4, -3, -2, -1, 0), T);
check('seven days earn a freeze', r.run === 7 && r.freezes === 1 && r.nextFreezeIn === 7, JSON.stringify(r));

r = computeRun(set(-8, -7, -6, -5, -4, -3, -2, 0), T);
check('a freeze covers a missed day without counting it', r.run === 8 && r.freezes === 0
    && r.frozen.has(T - 1) && r.frozen.size === 1, JSON.stringify({ ...r, frozen: [...r.frozen] }));

r = computeRun(set(-9, -8, -7, -6, -5, -4, -3, 0), T);
check('two misses with one freeze break the run', r.run === 1 && r.longest === 7, JSON.stringify(r));

const long = new Set();
for (let o = -40; o <= 0; o += 1) long.add(T + o);
r = computeRun(long, T);
check(`freezes are capped at ${FREEZE_MAX}`, r.freezes === FREEZE_MAX && r.nextFreezeIn === null, JSON.stringify(r));

check('week starts on Monday', dayString(weekStart(dayNumber('2026-10-01'))) === '2026-09-28'
    && dayString(weekStart(dayNumber('2026-09-28'))) === '2026-09-28'
    && dayString(weekStart(dayNumber('2026-10-04'))) === '2026-09-28');
check('day strings round-trip', dayString(dayNumber('2024-02-29')) === '2024-02-29' && Number.isNaN(dayNumber('nope'))
    && dayNumbers(['2026-10-01', 'junk']).size === 1);

