const parsed = parseRootReadme(README);
const keys = Object.keys(parsed).sort();
check('README rows come back under the sync path\'s keys', JSON.stringify(keys) === JSON.stringify([
    'AtCoder:abc300/abc300_a', 'Codeforces:1850-G', 'LeetCode:Odd Title', 'LeetCode:two-sum'
]), JSON.stringify(keys));
const twoSum = parsed['LeetCode:two-sum'];
check('a problem under two topics keeps both, once', twoSum.tags.join() === 'Array,Hash Table'
    && twoSum.date === '2026-09-22' && twoSum.difficulty === 'Easy'
    && twoSum.folderUrl === 'https://github.com/me/algos/tree/HEAD/LeetCode/Easy/Two Sum', JSON.stringify(twoSum));
const cf = parsed['Codeforces:1850-G'];
check('escaped titles and parenthesised folders survive', cf.title === 'Odd | Even [easy]'
    && cf.folderUrl.endsWith('/Odd Even (easy)') && cf.tags.length === 0, JSON.stringify(cf));
check('a junk README restores nothing', Object.keys(parseRootReadme('# My notes\n\n| a | b |')).length === 0);

const index = {
    'LeetCode:two-sum': {
        title: 'Two Sum', platform: 'LeetCode', difficulty: 'Easy', tags: [], link: 'https://leetcode.com/problems/two-sum/',
        folderUrl: 'https://github.com/me/algos/tree/HEAD/LeetCode/Easy/Two Sum', date: '2026-09-25', solvedAt: null,
        solutionPath: 'LeetCode/Easy/Two Sum/solution.py'
    },
    'Codeforces:1850-g-legacy': {
        title: 'Odd | Even [easy]', platform: 'Codeforces', difficulty: '800', tags: ['math'],
        link: 'https://codeforces.com/contest/1850/problem/G',
        folderUrl: 'https://github.com/me/algos/tree/HEAD/Codeforces/800/Odd Even (easy)', date: '2026-09-21'
    }
};
const added = mergeIntoIndex(index, parsed);
check('merge adds only what is missing', added === 2 && Object.keys(index).length === 4, `added=${added}`);
check('merge never overwrites what the index holds', index['LeetCode:two-sum'].date === '2026-09-25'
    && index['LeetCode:two-sum'].solutionPath === 'LeetCode/Easy/Two Sum/solution.py');
check('merge fills fields the index was missing', index['LeetCode:two-sum'].tags.join() === 'Array,Hash Table');
check('a different key for the same folder is not a duplicate', !index['Codeforces:1850-G']);

const fromServer = { 'LeetCode:two-sum': entryFromShared({
    key: 'LeetCode:two-sum', platform: 'LeetCode', title: 'Two Sum', difficulty: 'Easy', link: null,
    solutionUrl: null, solvedOn: '2026-09-22', solvedAt: 1758500000000
}) };
check('shared solves fill a missing live stamp', mergeIntoIndex(index, fromServer) === 0
    && index['LeetCode:two-sum'].solvedAt === 1758500000000);

/* ── milestones ────────────────────────────────────────────────────── */

const many = {};
for (let i = 0; i < 12; i += 1) many[`LeetCode:p${i}`] = { title: `p${i}`, platform: 'LeetCode', date: dayString(T - i) };
const m = milestonesFor(many, T);
check('milestones count solves and runs', m.total === 12 && m.run === 12
    && m.earned.map((e) => e.id).join() === 'solves-10,run-7' && m.next.solves.value === 25 && m.next.run.value === 14,
    JSON.stringify(m));

check('first look records milestones silently', (await takeNewMilestones(many)).length === 0
    && store.milestonesSeen.length === 2);
for (let i = 12; i < 26; i += 1) many[`LeetCode:p${i}`] = { title: `p${i}`, platform: 'LeetCode', date: dayString(T - i) };
const fresh = await takeNewMilestones(many);
check('new milestones come back highest first', fresh.map((f) => f.id).join() === 'solves-25,run-14', JSON.stringify(fresh));
check('each milestone is announced once', (await takeNewMilestones(many)).length === 0);

console.log(failures ? `\n${failures} failing` : '\nall passing');
if (failures) process.exitCode = 1;
